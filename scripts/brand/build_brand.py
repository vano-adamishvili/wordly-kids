"""Builds the Wivilo wordmark + logo SVGs from Fredoka (OFL) glyph outlines.
Output: src/components/brand/wordmark.ts, public/brand/*.svg
Run: bash scripts/brand/build.sh"""
import re, json, pathlib
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = pathlib.Path(__file__).resolve().parents[2]
font = TTFont(ROOT / "node_modules/@fontsource-variable/fredoka/files/fredoka-latin-wght-normal.woff2")
font = instantiateVariableFont(font, {"wght": 640})
gs = font.getGlyphSet(); cmap = font.getBestCmap(); hmtx = font["hmtx"]
X_HEIGHT = font["OS/2"].sxHeight or 500

INK = "#6A4FD0"      # wordmark colour (deep lavender – AA on cream)
DOT1 = "#FFD85A"     # sunny yellow tuft (Wivi's)
DOT1_DARK = "#E5B400"
DOT2 = "#FF8D85"     # coral dot

def glyph(ch):
    name = cmap[ord(ch)]
    bp = BoundsPen(gs); gs[name].draw(bp)
    return name, hmtx[name][0], bp.bounds

# stem width from the letter l
_, _, lb = glyph("l"); STEM = lb[2] - lb[0]
TRACK = -18
parts, x = [], 0.0
dots = []
for ch in "wivilo":
    if ch == "i":
        w = STEM + 70
        x0 = x + 35
        r = STEM / 2
        # stem: rounded rectangle from baseline to x-height (y up)
        parts.append(f"M{x0:.1f},{-r:.1f} V{-(X_HEIGHT - r):.1f} A{r:.1f},{r:.1f} 0 0 1 {x0+STEM:.1f},{-(X_HEIGHT - r):.1f} V{-r:.1f} A{r:.1f},{r:.1f} 0 0 1 {x0:.1f},{-r:.1f} Z")
        dots.append((x0 + STEM / 2, -(X_HEIGHT + STEM * 0.9), STEM * 0.56))
        x += w + TRACK
        continue
    name, adv, b = glyph(ch)
    pen = SVGPathPen(gs)
    tp = TransformPen(pen, (1, 0, 0, -1, x, 0))
    gs[name].draw(tp)
    parts.append(pen.getCommands())
    x += adv + TRACK
width = x - TRACK
_, _, lb2 = glyph("l")
top = min(min(d[1] - d[2] for d in dots) - 30, -lb2[3] - 20)
height = -top + 20
path = " ".join(parts)

def tuft(cx, cy, r):
    s = r / 34
    return (f'<g transform="translate({cx:.1f} {cy+r*0.15:.1f}) scale({s:.3f})">'
            f'<path d="M0 30 C0 18 2 8 4 0" stroke="{DOT1_DARK}" stroke-width="7" stroke-linecap="round" fill="none"/>'
            f'<path d="M2 6 C-10 -14 -30 -16 -40 -4 C-28 12 -10 14 2 6Z" fill="{DOT1}"/>'
            f'<path d="M5 3 C14 -20 38 -24 48 -12 C38 6 16 10 5 3Z" fill="{DOT1}"/></g>')

def dots_svg():
    (x1, y1, r1), (x2, y2, r2) = dots
    return tuft(x1, y1 + r1 * 0.2, r1 * 1.25) + f'<circle cx="{x2:.1f}" cy="{y2:.1f}" r="{r2:.1f}" fill="{DOT2}"/>'

VB = f"0 {top:.0f} {width:.0f} {height:.0f}"
wordmark_inner = f'<path d="{path}" fill="{INK}"/>{dots_svg()}'
(ROOT / "public/brand/wivilo-wordmark.svg").write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VB}" role="img" aria-label="Wivilo">{wordmark_inner}</svg>\n')

# TS module for the React logo component
out = ROOT / "src/components/brand"; out.mkdir(parents=True, exist_ok=True)
(out / "wordmark.ts").write_text(
    "// Generated by scripts/brand/build_brand.py — Fredoka (OFL) outlines + custom i-dots\n"
    f"export const WORDMARK_VIEWBOX = {json.dumps(VB)};\n"
    f"export const WORDMARK_PATH = {json.dumps(path)};\n"
    f"export const WORDMARK_INK = {json.dumps(INK)};\n"
    f"export const WORDMARK_DOTS_SVG = {json.dumps(dots_svg())};\n"
    f"export const WORDMARK_RATIO = {width/height:.4f};\n")

# Wivi svg (cropped) for logos & icons
def wivi(mood):
    s = pathlib.Path(f"/tmp/wivi-{mood}.svg").read_text()
    s = re.sub(r'width="\d+" height="\d+"', "", s, count=1)
    s = re.sub(r'class="[^"]*"', "", s, count=1)
    s = s.replace('viewBox="0 0 200 200"', 'viewBox="20 6 160 186"', 1)
    return s
def nest(svg, x, y, w, h):
    return svg.replace("<svg", f'<svg x="{x}" y="{y}" width="{w}" height="{h}"', 1)

wm_h = 200; wm_w = wm_h * (width / height)
wm_nested = (f'<svg x="236" y="{(260-wm_h)/2+14:.1f}" width="{wm_w:.1f}" height="{wm_h}" viewBox="{VB}">{wordmark_inner}</svg>')
LOGO_W = 236 + wm_w + 16
(ROOT / "public/brand/wivilo-logo.svg").write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {LOGO_W:.0f} 260" role="img" aria-label="Wivilo">'
    f'{nest(wivi("happy"), 10, 10, 206, 240)}{wm_nested}</svg>\n')

def app_icon(bg="#EFEAFD"):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">'
            f'<rect width="512" height="512" rx="112" fill="{bg}"/>'
            f'<circle cx="420" cy="92" r="46" fill="#FFD85A" opacity="0.55"/>'
            f'<circle cx="74" cy="440" r="64" fill="#72D9B3" opacity="0.35"/>'
            f'{nest(wivi("happy"), 76, 58, 360, 418)}</svg>\n')
(ROOT / "public/brand/wivilo-app-icon.svg").write_text(app_icon())
# compact mark: Wivi without background
(ROOT / "public/brand/wivilo-mark.svg").write_text(nest(wivi("happy"), 0, 0, 160, 186).replace('x="0" y="0" ', "", 1).replace("<svg", '<svg role="img" aria-label="Wivilo"', 1) + "\n")
# favicon svg (same as app icon, Next uses src/app/icon.svg)
(ROOT / "src/app/icon.svg").write_text(app_icon())

og = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 630">'
      f'<rect width="1200" height="630" fill="#FAF8F3"/>'
      f'<circle cx="1120" cy="70" r="190" fill="#EFEAFD"/><circle cx="60" cy="600" r="170" fill="#E2F7EF"/>'
      f'<circle cx="1010" cy="560" r="90" fill="#FFF5D1"/>'
      f'{nest(wivi("cheering"), 70, 120, 330, 384)}'
      f'<svg x="450" y="130" width="620" height="{620/(width/height):.0f}" viewBox="{VB}">{wordmark_inner}</svg>'
      f'<text x="456" y="{150+620/(width/height)+40:.0f}" font-family="Noto Sans Georgian, sans-serif" font-weight="800" font-size="36" fill="#252442">ისწავლე. ითამაშე. განვითარდი.</text>'
      f'<text x="456" y="{150+620/(width/height)+100:.0f}" font-family="Fredoka, Nunito, sans-serif" font-weight="600" font-size="34" fill="#6A4FD0">Learn. Play. Grow.</text>'
      f'<text x="456" y="{150+620/(width/height)+160:.0f}" font-family="Noto Sans Georgian, sans-serif" font-weight="600" font-size="28" fill="#5d5b7a">ინგლისური სიტყვები 6–10 წლის ბავშვებისთვის</text>'
      f'</svg>\n')
(ROOT / "public/brand/wivilo-og.svg").write_text(og)
(ROOT / "/tmp/logo_w.txt").write_text(str(round(LOGO_W)))
print("brand svgs written; wordmark", round(width), "x", round(height))
